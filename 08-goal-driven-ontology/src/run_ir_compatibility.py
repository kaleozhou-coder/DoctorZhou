"""Retrospective compatibility audit, not a model run or hidden evaluation."""
import argparse
import hashlib
import json
from pathlib import Path
from rule_ir import loads, predict_case
from benchmark_eval import verify_freeze


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(path, obj):
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2, allow_nan=False) + '\n')


def run(project, artifact_path, family, freeze_path, output):
    if family not in {f"F{i:02d}" for i in range(1, 7)}:
        raise ValueError("Unknown benchmark family")
    if output.exists() and any(output.iterdir()):
        raise ValueError("Output must be empty; preserve prior runs")
    freeze = json.loads(freeze_path.read_text())
    files = freeze["sha256"]
    for name in ("src/rule_ir.py", str(artifact_path.relative_to(project))):
        if name not in files:
            raise ValueError("Freeze must cover interpreter and artifact")
    for name, expected in files.items():
        path = project / name
        if not path.resolve().is_relative_to(project.resolve()) or sha(path) != expected:
            raise ValueError("Invalid path or changed frozen file: " + name)
    artifact = loads(artifact_path.read_text())
    benchmark = project / "benchmark/v1"
    verify_freeze(benchmark)  # Integrity hashing only; does not parse labels.
    materials = json.loads((benchmark / "model-facing" / family / "materials.json").read_text())
    cases_path = benchmark / "evaluator/inputs" / (family + ".json")
    cases = json.loads(cases_path.read_text())["cases"]
    case_ids = [c.get("case_id") for c in cases]
    if any(type(x) is not str or not x for x in case_ids) or len(set(case_ids)) != len(case_ids):
        raise ValueError("Invalid or duplicate input case IDs")
    predictions = [predict_case(case, artifact, materials) for case in cases]
    output.mkdir(parents=True, exist_ok=True)
    write(output / "predictions.json", {
        "execution_kind": "retrospective_manual_artifact_compatibility",
        "model_calls": 0, "family": family,
        "freeze_sha256": sha(freeze_path),
        "artifact_sha256": sha(artifact_path),
        "case_input_sha256": sha(cases_path),
        "predictions": predictions,
    })
    # All predictions persisted before semantic label access.
    labels = json.loads((benchmark / "evaluator/labels.json").read_text())["cases"]
    label_ids = [row.get("case_id") for row in labels]
    prediction_ids = [row.get("case_id") for row in predictions]
    for ids in (label_ids, prediction_ids):
        if any(type(x) is not str or not x for x in ids) or len(set(ids)) != len(ids):
            raise ValueError("Invalid or duplicate label/prediction IDs")
    selected = {row["case_id"]: row for row in labels if row["family_id"] == family}
    if set(selected) != {p["case_id"] for p in predictions}:
        raise ValueError("Prediction/label IDs do not match")
    rows = []
    for prediction in predictions:
        label = selected[prediction["case_id"]]
        rows.append({
            "case_id": prediction["case_id"], "predicted": prediction["decision"],
            "expected": label["expected_decision"], "decision_correct": prediction["decision"] == label["expected_decision"],
            "predicted_reasons": prediction["reason_codes"],
            "expected_reasons": label["required_reason_codes"],
            "reason_correct": prediction["reason_codes"] == label["required_reason_codes"],
        })
    summary = {
        "execution_kind": "retrospective_manual_artifact_compatibility", "model_calls": 0,
        "family": family, "existing_benchmark_cases": len(labels), "executed_cases": len(rows),
        "unsupported_not_executed_cases": len(labels) - len(rows),
        "decision_correct": sum(x["decision_correct"] for x in rows),
        "primary_reason_correct": sum(x["reason_correct"] for x in rows),
        "unsafe_close_n": sum(x["predicted"] == "close_eligible" and x["expected"] != "close_eligible" for x in rows),
        "negative_n": sum(x["expected"] != "close_eligible" for x in rows),
        "close_recall_n": sum(x["predicted"] == x["expected"] == "close_eligible" for x in rows),
        "positive_n": sum(x["expected"] == "close_eligible" for x in rows),
        "labels_sha256": sha(benchmark / "evaluator/labels.json"),
        "predictions_sha256": sha(output / "predictions.json"),
        "limitations": [
            "Artifact authored by research implementation, not generated by either model arm.",
            "Existing cases are retrospective engineering checks, not unseen or independent generalization.",
            f"Unsupported cases are not included in correctness denominator; coverage explicitly reports all {len(labels)} cases.",
            "Labels are synthetic author labels, not expert gold. Locator checks are not semantic support."
        ],
        "rows": rows,
    }
    write(output / "summary.json", summary)
    return summary


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact", type=Path, required=True)
    parser.add_argument("--family", required=True)
    parser.add_argument("--freeze", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    project = Path(__file__).resolve().parents[1]
    print(json.dumps(run(project, args.artifact.resolve(), args.family, args.freeze, args.output), indent=2))
